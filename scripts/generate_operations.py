#!/usr/bin/env python3
"""Write src/asao_erp/operations.py from the catalog the CLI publishes (`odoo catalog list`).

Every operation becomes an attribute of its family, so an editor completes it and shows what it is:
ops.sales.quotation_list is "sales.quotation.list", a READ, CURRENT_VERIFIED.

    scripts/generate_operations.py [--odoo-bin odoo]
"""
import argparse
import json
import keyword
import subprocess
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "asao_erp" / "operations.py"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--odoo-bin", default="odoo-cli")
    options = parser.parse_args()
    listing = json.loads(subprocess.run([options.odoo_bin, "catalog", "list", "--output", "json"],
                                        capture_output=True, text=True, check=True).stdout)
    families = defaultdict(list)
    for item in listing["data"]["items"]:
        family, rest = item["id"].split(".", 1)
        name = rest.replace(".", "_")
        if keyword.iskeyword(name):
            name += "_"
        families[family].append((name, item))
    lines = [
        "# Code generated by scripts/generate_operations.py from `odoo catalog list`. DO NOT EDIT.",
        '"""Every catalog operation, by family, for completion: ops.sales.quotation_list."""',
        "",
        "",
        "class Operation(str):",
        '    """An operation id, carrying what the catalog says of it."""',
        "",
        "    kind: str",
        "    strategy: str",
        "    readiness: str",
        "",
        "    def __new__(cls, operation_id: str, kind: str, strategy: str, readiness: str):",
        "        operation = super().__new__(cls, operation_id)",
        "        operation.kind, operation.strategy, operation.readiness = kind, strategy, readiness",
        "        return operation",
        "",
    ]
    for family in sorted(families):
        members = sorted(families[family])
        attribute = family + "_" if keyword.iskeyword(family) else family
        lines += ["", f"class {attribute}:", f'    """{family}: {len(members)} operations."""', ""]
        for name, item in members:
            lines.append(f'    {name} = Operation({json.dumps(item["id"])}, {json.dumps(item["kind"])}, '
                         f'{json.dumps(item["strategy"])}, {json.dumps(item["readiness"])})')
    lines += ["", "", "FAMILIES = (" + ", ".join(f + "_" if keyword.iskeyword(f) else f for f in sorted(families)) + ",)", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{sum(len(m) for m in families.values())} operations in {len(families)} families -> {OUT}")


if __name__ == "__main__":
    main()
